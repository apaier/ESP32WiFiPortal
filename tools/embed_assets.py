#!/usr/bin/env python3
"""Embed every file in data/ as a PROGMEM byte array under src/generated/.

Runs automatically as part of the library's PlatformIO build via the
build.extraScript hook in library.json. Arduino IDE has no comparable
hook, so users on that toolchain must run this script manually after
editing anything in data/.

See docs/embedded-assets.md for the rationale.
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

try:
    _here = Path(__file__).resolve()
except NameError:
    # PlatformIO's SConscript runner exec's this file without setting
    # __file__. Recover the path from the current frame's code object.
    _here = Path(inspect.currentframe().f_code.co_filename).resolve()
REPO_ROOT = _here.parents[1]
DATA_DIR = REPO_ROOT / "data"
OUT_DIR = REPO_ROOT / "src" / "generated"
HEADER_PATH = OUT_DIR / "embedded_assets.h"
SOURCE_PATH = OUT_DIR / "embedded_assets.cpp"


def symbol_for(rel_path: str) -> str:
    s = re.sub(r"[^0-9A-Za-z]", "_", rel_path)
    if s and s[0].isdigit():
        s = "_" + s
    return s


def collect_assets() -> list[tuple[str, bytes]]:
    if not DATA_DIR.is_dir():
        return []
    out: list[tuple[str, bytes]] = []
    for path in sorted(DATA_DIR.rglob("*")):
        if not path.is_file():
            continue
        if path.name.startswith("."):
            continue
        rel = path.relative_to(DATA_DIR).as_posix()
        out.append((rel, path.read_bytes()))
    return out


def format_bytes(data: bytes, indent: str = "    ") -> str:
    if not data:
        return indent + "0x00,  // placeholder; zero-length asset"
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def render_header(assets: list[tuple[str, bytes]]) -> str:
    decls = []
    for rel, _ in assets:
        sym = symbol_for(rel)
        decls.append(f"extern const uint8_t {sym}[];")
        decls.append(f"extern const size_t {sym}_len;")
    body = "\n".join(decls) + "\n\n" if decls else ""
    return (
        "// AUTOGENERATED by tools/embed_assets.py. Do not edit by hand.\n"
        "// Edit the source files under data/ and re-run the script.\n"
        "#ifndef ESP32_WIFI_PORTAL_EMBEDDED_ASSETS_H\n"
        "#define ESP32_WIFI_PORTAL_EMBEDDED_ASSETS_H\n"
        "\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "\n"
        + body
        + "// Look up an embedded asset by its path under data/, e.g.\n"
        "// \"WiFiSetup.html\" or \"subdir/file.json\". Returns a pointer to the\n"
        "// bytes (not null-terminated) and writes the length through outLen.\n"
        "// Returns nullptr if the name doesn't match any embedded asset.\n"
        "const uint8_t* getEmbeddedAsset(const char* name, size_t* outLen);\n"
        "\n"
        "#endif  // ESP32_WIFI_PORTAL_EMBEDDED_ASSETS_H\n"
    )


def render_source(assets: list[tuple[str, bytes]]) -> str:
    defs = []
    for rel, data in assets:
        sym = symbol_for(rel)
        defs.append(
            f"const uint8_t {sym}[] PROGMEM = {{\n"
            f"{format_bytes(data)}\n"
            f"}};\n"
            f"const size_t {sym}_len = {len(data)};\n"
        )

    if assets:
        entries = ",\n".join(
            f"    {{ \"{rel}\", {symbol_for(rel)}, &{symbol_for(rel)}_len }}"
            for rel, _ in assets
        )
        table = (
            "namespace {\n"
            "struct AssetEntry {\n"
            "    const char* name;\n"
            "    const uint8_t* data;\n"
            "    const size_t* len;\n"
            "};\n"
            "const AssetEntry kAssetTable[] = {\n"
            f"{entries}\n"
            "};\n"
            "constexpr size_t kAssetCount = sizeof(kAssetTable) / sizeof(kAssetTable[0]);\n"
            "}  // namespace\n"
            "\n"
            "const uint8_t* getEmbeddedAsset(const char* name, size_t* outLen) {\n"
            "    if (name == nullptr) return nullptr;\n"
            "    for (size_t i = 0; i < kAssetCount; ++i) {\n"
            "        if (strcmp(kAssetTable[i].name, name) == 0) {\n"
            "            if (outLen != nullptr) *outLen = *kAssetTable[i].len;\n"
            "            return kAssetTable[i].data;\n"
            "        }\n"
            "    }\n"
            "    return nullptr;\n"
            "}\n"
        )
    else:
        table = (
            "const uint8_t* getEmbeddedAsset(const char* /*name*/, size_t* /*outLen*/) {\n"
            "    return nullptr;\n"
            "}\n"
        )

    return (
        "// AUTOGENERATED by tools/embed_assets.py. Do not edit by hand.\n"
        "// Edit the source files under data/ and re-run the script.\n"
        "#include \"embedded_assets.h\"\n"
        "\n"
        "#include <Arduino.h>\n"
        "#include <string.h>\n"
        "\n"
        + "\n".join(defs)
        + "\n"
        + table
    )


def write_if_changed(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text() == content:
        return False
    path.write_text(content)
    return True


def main() -> int:
    assets = collect_assets()
    changed = write_if_changed(HEADER_PATH, render_header(assets))
    changed = write_if_changed(SOURCE_PATH, render_source(assets)) or changed
    summary = ", ".join(f"{rel} ({len(data)} B)" for rel, data in assets) or "(none)"
    state = "regenerated" if changed else "up to date"
    print(f"[embed_assets] {state}: {summary}")
    return 0


# Executed unconditionally so PlatformIO's extraScript hook (which imports
# this file) triggers regeneration before the library compiles. Re-running
# manually as `python tools/embed_assets.py` is also supported.
main()


if __name__ == "__main__":
    sys.exit(0)
